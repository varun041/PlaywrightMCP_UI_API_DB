/**
 * Reads reports/allure-results after a test run and writes a synthetic Allure result entry
 * ("AI Run Summary") whose description is a short plain-English summary of the run — total
 * pass/fail counts, and critically, which failures are already-known/accepted gaps (tagged
 * @KnownGap in the feature files) versus new regressions that need triage.
 *
 * Runs before `allure generate` so the summary appears as a normal (always-green, "Meta" suite)
 * entry inside the generated report itself, rather than a separate file nobody opens. Also mirrors
 * the same text to reports/run-summary.md for quick viewing / CI artifact upload without opening
 * the full Allure report.
 */
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const RESULTS_DIR = path.join(__dirname, '..', 'reports', 'allure-results');
const SUMMARY_MD_PATH = path.join(__dirname, '..', 'reports', 'run-summary.md');
const SUMMARY_TAG = 'ai-run-summary';

// reports/allure-results is cumulative across every run ever executed locally (Allure itself
// aggregates the whole directory), so without this window the summary would report on months of
// history instead of "this run." Anything that finished within RUN_WINDOW_MS of the single most
// recent result is treated as belonging to the same run.
const RUN_WINDOW_MS = 15 * 60 * 1000;

function readResults() {
  if (!fs.existsSync(RESULTS_DIR)) return [];
  return fs
    .readdirSync(RESULTS_DIR)
    .filter((f) => f.endsWith('-result.json'))
    .map((f) => {
      const fullPath = path.join(RESULTS_DIR, f);
      return {
        file: f,
        mtimeMs: fs.statSync(fullPath).mtimeMs,
        data: JSON.parse(fs.readFileSync(fullPath, 'utf8')),
      };
    });
}

function isSummaryEntry(entry) {
  return (entry.labels || []).some((l) => l.name === 'tag' && l.value === SUMMARY_TAG);
}

// Summary entries from prior runs must be removed first — otherwise they'd both pollute this
// run's stats and pile up as duplicate "AI Run Summary" rows in every future report.
function purgeOldSummaries(results) {
  for (const { file, data } of results) {
    if (isSummaryEntry(data)) {
      fs.unlinkSync(path.join(RESULTS_DIR, file));
    }
  }
}

function tagsOf(entry) {
  return (entry.labels || []).filter((l) => l.name === 'tag').map((l) => l.value);
}

function projectOf(entry) {
  const param = (entry.parameters || []).find((p) => p.name === 'Project');
  if (param) return param.value;
  const suiteLabel = (entry.labels || []).find((l) => l.name === 'parentSuite');
  return suiteLabel ? suiteLabel.value : 'unknown';
}

function firstErrorLine(entry) {
  const msg = entry.statusDetails && entry.statusDetails.message;
  if (!msg) return null;
  return msg.split('\n')[0].slice(0, 160);
}

function buildSummary(realResults) {
  const total = realResults.length;
  const byStatus = { passed: 0, failed: 0, broken: 0, skipped: 0, unknown: 0 };
  for (const r of realResults) {
    byStatus[r.status] = (byStatus[r.status] ?? 0) + 1;
  }

  const failing = realResults.filter((r) => r.status === 'failed' || r.status === 'broken');
  const knownGaps = failing.filter((r) => tagsOf(r).includes('KnownGap'));
  const regressions = failing.filter((r) => !tagsOf(r).includes('KnownGap'));

  const lines = [];
  lines.push('# Run Summary');
  lines.push('');
  lines.push(`_Generated ${new Date().toISOString()}_`);
  lines.push('');
  lines.push(
    `**${total} scenario executions** — ${byStatus.passed} passed, ${byStatus.failed} failed, ` +
      `${byStatus.broken} broken, ${byStatus.skipped} skipped.`
  );
  lines.push('');

  if (regressions.length > 0) {
    lines.push(`## ⚠ New regressions requiring triage (${regressions.length})`);
    for (const r of regressions) {
      const err = firstErrorLine(r);
      lines.push(`- **${r.name}** (${projectOf(r)})${err ? ` — ${err}` : ''}`);
    }
  } else {
    lines.push('## New regressions requiring triage');
    lines.push(
      'None — every failure this run (if any) is an already-tracked known gap, or there were no failures.'
    );
  }
  lines.push('');

  if (knownGaps.length > 0) {
    lines.push(`## Known gaps — tracked, no action needed (${knownGaps.length})`);
    for (const r of knownGaps) {
      lines.push(`- **${r.name}** (${projectOf(r)}) — tagged \`@KnownGap\`, see Requirement.md / TestScenarios.md.`);
    }
    lines.push('');
  }

  if (byStatus.skipped > 0) {
    const skipped = realResults.filter((r) => r.status === 'skipped');
    lines.push(`## Skipped (${byStatus.skipped})`);
    for (const r of skipped) {
      lines.push(`- ${r.name} (${projectOf(r)})`);
    }
    lines.push('');
  }

  lines.push('---');
  lines.push(
    '_Auto-generated by `scripts/generate-run-summary.js` — classifies failures against `@KnownGap` tags ' +
      'so triage only has to look at genuinely new breakage._'
  );

  return { markdown: lines.join('\n'), total, byStatus, regressions, knownGaps };
}

function writeSummaryResult(markdown) {
  const nowMs = Date.now();
  const result = {
    uuid: crypto.randomUUID(),
    historyId: 'ai-run-summary',
    name: 'AI Run Summary',
    fullName: 'AI Run Summary',
    status: 'passed',
    stage: 'finished',
    description: markdown,
    labels: [
      { name: 'suite', value: 'Meta' },
      { name: 'parentSuite', value: 'Meta' },
      { name: 'subSuite', value: 'AI Run Summary' },
      { name: 'severity', value: 'normal' },
      { name: 'tag', value: SUMMARY_TAG },
    ],
    start: nowMs,
    stop: nowMs,
  };
  fs.mkdirSync(RESULTS_DIR, { recursive: true });
  fs.writeFileSync(path.join(RESULTS_DIR, `${result.uuid}-result.json`), JSON.stringify(result, null, 2));
}

// Best-effort fallback for standalone use (no known invocation start time): cluster by proximity
// of each result file's own mtime to the single most recent one.
function latestRunByProximity(entries) {
  if (entries.length === 0) return entries;
  const latest = Math.max(...entries.map((e) => e.mtimeMs));
  return entries.filter((e) => e.mtimeMs >= latest - RUN_WINDOW_MS);
}

// Precise path: only result files written at/after the moment this test invocation started.
function latestRunSince(entries, sinceMs) {
  // Small negative buffer absorbs clock/filesystem timestamp granularity, not a real window guess.
  return entries.filter((e) => e.mtimeMs >= sinceMs - 2000);
}

function main() {
  const results = readResults();
  purgeOldSummaries(results);
  const allEntries = results.filter((r) => !isSummaryEntry(r.data));

  const sinceMs = process.env.RUN_SUMMARY_SINCE_MS ? Number(process.env.RUN_SUMMARY_SINCE_MS) : null;
  const scopedEntries = sinceMs ? latestRunSince(allEntries, sinceMs) : latestRunByProximity(allEntries);
  const realResults = scopedEntries.map((e) => e.data);

  const { markdown, total, byStatus, regressions, knownGaps } = buildSummary(realResults);

  writeSummaryResult(markdown);
  fs.mkdirSync(path.dirname(SUMMARY_MD_PATH), { recursive: true });
  fs.writeFileSync(SUMMARY_MD_PATH, markdown);

  console.log(markdown);
  console.log('');
  console.log(
    `[generate-run-summary] ${total} total, ${byStatus.passed} passed, ` +
      `${regressions.length} new regression(s), ${knownGaps.length} known gap(s).`
  );
}

main();
